H1 = 'sha256:' + 'a' * 64
H2 = 'sha256:' + 'b' * 64

MANIFEST = {
    'type': 'probe',
    'version': '1.0.0',
    'lager_api': 1,
    'requirements': 'requirements.txt',
    'actions': {'ping': {}},
}
DRIVER = (
    'from lager.drivers import CustomDriver, action\n'
    'class Driver(CustomDriver):\n'
    '    @action\n'
    '    def ping(self):\n'
    '        import lagertestpkg\n'
    '        return {"message": lagertestpkg.hello()}\n'
)


def make_bundle(requirements: 'str | None' = 'crcmod==1.7 --hash=%s\n' % H1, extra=None,
                manifest=None):
    files = {'lager_driver.json': json.dumps(manifest or MANIFEST), 'driver.py': DRIVER}
    if requirements is not None:
        files['requirements.txt'] = requirements
    files.update(extra or {})
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, 'w') as z:
        for name, content in files.items():
            z.writestr(name, content)
    return buf.getvalue()


def make_wheel(name='lagertestpkg', version='0.1.0', requires=()):
    """A minimal pure-Python wheel; returns (filename, bytes)."""
    dist = '%s-%s.dist-info' % (name, version)
    files = {
        '%s/__init__.py' % name: 'def hello():\n    return "hello from %s"\n' % name,
        '%s/METADATA' % dist: 'Metadata-Version: 2.1\nName: %s\nVersion: %s\n%s' % (
            name, version, ''.join('Requires-Dist: %s\n' % r for r in requires)),
        '%s/WHEEL' % dist: 'Wheel-Version: 1.0\nGenerator: test\nRoot-Is-Purelib: true\n'
                           'Tag: py3-none-any\n',
    }
    record = []
    for path, content in files.items():
        digest = base64.urlsafe_b64encode(
            hashlib.sha256(content.encode()).digest()).rstrip(b'=').decode()
        record.append('%s,sha256=%s,%d' % (path, digest, len(content.encode())))
    record.append('%s/RECORD,,' % dist)
    files['%s/RECORD' % dist] = '\n'.join(record) + '\n'
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, 'w') as z:
        for path, content in files.items():
            z.writestr(path, content)
    return '%s-%s-py3-none-any.whl' % (name, version), buf.getvalue()


def fake_dist(target, name, version, requires=()):
    info = os.path.join(target, '%s-%s.dist-info' % (name, version))
    os.makedirs(info)
    with open(os.path.join(info, 'METADATA'), 'w') as f:
        f.write('Metadata-Version: 2.1\nName: %s\nVersion: %s\n' % (name, version))
        for r in requires:
            f.write('Requires-Dist: %s\n' % r)


class TestParseRequirements(unittest.TestCase):
    def test_pip_compile_output(self):
        text = (
            '#\n# This file is autogenerated by pip-compile\n#\n'
            'crcmod==1.7 \\\n'
            '    --hash=%s \\\n'
            '    --hash=%s\n'
            '    # via -r requirements.in\n'
            'Py_Serial-Extra[fast]==2.0.1 --hash %s  # trailing comment\n' % (H1, H2, H1)
        )
        reqs = deps.parse_requirements(text)
        self.assertEqual([(r['name'], r['version']) for r in reqs],
                         [('crcmod', '1.7'), ('py-serial-extra', '2.0.1')])
        self.assertEqual(reqs[0]['line'], 'crcmod==1.7 --hash=%s --hash=%s' % (H1, H2))
        self.assertIn('--hash=%s' % H1, reqs[1]['line'])

    def test_marker_for_another_python_is_skipped(self):
        reqs = deps.parse_requirements(
            'tomli==2.0.1 ; python_version < "3.0" --hash=%s\n' % H1)
        self.assertEqual(reqs, [])

    def test_rejections(self):
        cases = {
            'crcmod --hash=%s' % H1: 'pinned',
            'crcmod>=1.7 --hash=%s' % H1: 'pinned',
            'crcmod==1.* --hash=%s' % H1: 'pinned',
            'crcmod==1.7': '--hash',
            'crcmod==1.7 --hash=md5:abc': 'bad hash',
            '-r other.txt': "'-r' is not allowed",
            '--index-url https://example.invalid/simple': 'not allowed',
            '-e git+https://example.invalid/x.git': 'not allowed',
            'crcmod==1.7 --hash=%s --extra-index-url x' % H1: 'not allowed',
            'pkg @ https://example.invalid/pkg.whl --hash=%s' % H1: 'URL',
            'crcmod==1.7 --hash=%s\nCRCMOD==1.7 --hash=%s' % (H1, H1): 'twice',
        }
        for text, why in cases.items():
            with self.subTest(text=text), self.assertRaisesRegex(deps.DepsError, why) as cm:
                deps.parse_requirements(text)
            self.assertEqual(cm.exception.status, 400)


class TestAgainstBox(unittest.TestCase):
    def reqs(self, *pins):
        return [{'name': deps.normalize(n), 'version': v, 'line': '%s==%s' % (n, v)}
                for n, v in pins]

    def test_same_version_is_dropped_new_is_kept(self):
        install, skipped = deps.split_against_box(
            self.reqs(('requests', '2.32.3'), ('crcmod', '1.7')), {'requests': '2.32.3'})
        self.assertEqual([r['name'] for r in install], ['crcmod'])
        self.assertEqual([r['name'] for r in skipped], ['requests'])

    def test_different_version_of_a_box_package_is_refused(self):
        with self.assertRaisesRegex(deps.DepsError, r'requests==2\.31\.0 \(the box has 2\.32\.3\)'):
            deps.split_against_box(self.reqs(('requests', '2.31.0')), {'requests': '2.32.3'})

    def test_box_packages_reads_this_environment(self):
        self.assertIn('pip', deps.box_packages())


class TestCheckComplete(unittest.TestCase):
    def setUp(self):
        self.target = tempfile.mkdtemp()
        self.addCleanup(shutil.rmtree, self.target, True)

    def test_dependency_in_deps_or_box_passes(self):
        fake_dist(self.target, 'alpha', '1.0', ['beta>=1', 'requests', 'gamma; extra == "x"'])
        fake_dist(self.target, 'beta', '1.2')
        deps.check_complete(self.target, {'requests': '2.32.3'})

    def test_missing_or_wrong_version_is_named(self):
        fake_dist(self.target, 'alpha', '1.0', ['beta>=2', 'delta'])
        fake_dist(self.target, 'beta', '1.2')
        with self.assertRaisesRegex(deps.DepsError, r'alpha needs beta \(have 1\.2\); '
                                                    r'alpha needs delta'):
            deps.check_complete(self.target, {})


class RegistryCase(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.mkdtemp()
        self._orig = registry.DRIVERS_DIR
        registry.DRIVERS_DIR = os.path.join(self.tmp, 'drivers')

    def tearDown(self):
        registry.DRIVERS_DIR = self._orig
        shutil.rmtree(self.tmp, ignore_errors=True)


def pip_ok(cmd, **_kw):
    """Stands in for pip: 'installs' a dist-info for each pinned line."""
    target = cmd[cmd.index('--target') + 1]
    with open(cmd[cmd.index('-r') + 1]) as f:
        for line in f:
            name, version = line.split()[0].split('==')
            fake_dist(target, name, version)
    return subprocess.CompletedProcess(cmd, 0, stdout='Successfully installed\n')


class TestRegistryWithDeps(RegistryCase):
    def test_install_runs_pip_into_staged_deps(self):
        with mock.patch.object(deps.subprocess, 'run', side_effect=pip_ok) as run:
            result = registry.install('probe', make_bundle(
                extra={'wheels/crcmod-1.7-py3-none-any.whl': 'x'}))
        self.assertEqual(result['packages'], ['crcmod==1.7'])
        cmd = run.call_args[0][0]
        for flag in ('--only-binary=:all:', '--require-hashes', '--no-deps', '--find-links'):
            self.assertIn(flag, cmd)
        self.assertNotIn('--no-index', cmd)
        self.assertEqual(run.call_args[1]['timeout'], deps.DEPS_TIMEOUT_S)

        entry = registry.get_driver('probe')
        self.assertEqual(entry['deps']['status'], 'ok')
        self.assertEqual(entry['deps']['packages'], ['crcmod==1.7'])
        stamp = os.path.join(registry.driver_dir('probe'), deps.DEPS_DIR, deps.STAMP_FILE)
        self.assertTrue(os.path.isfile(stamp))

    def test_offline_mode_adds_no_index(self):
        with mock.patch.dict(os.environ, {'LAGER_DRIVERS_OFFLINE': '1'}), \
                mock.patch.object(deps.subprocess, 'run', side_effect=pip_ok) as run:
            registry.install('probe', make_bundle())
        self.assertIn('--no-index', run.call_args[0][0])

    def test_packages_the_box_has_skip_pip(self):
        version = deps.box_packages()['pip']
        with mock.patch.object(deps.subprocess, 'run') as run:
            result = registry.install('probe', make_bundle(
                requirements='pip==%s --hash=%s\n' % (version, H1)))
        run.assert_not_called()
        self.assertEqual(result['packages'], [])
        self.assertEqual(registry.get_driver('probe')['deps']['status'], 'ok')

    def test_pip_failure_keeps_previous_version_live(self):
        with mock.patch.object(deps.subprocess, 'run', side_effect=pip_ok):
            registry.install('probe', make_bundle())
        failed = subprocess.CompletedProcess([], 1, stdout=(
            'Looking in links: wheels\n'
            "WARNING: Retrying ... NewConnectionError('Failed to establish a new connection')\n"
            'ERROR: Could not find a version that satisfies the requirement crcmod==1.8\n'))
        bumped = dict(MANIFEST, version='2.0.0')
        with mock.patch.object(deps.subprocess, 'run', return_value=failed), \
                self.assertRaises(registry.DriverStoreError) as cm:
            registry.install('probe', make_bundle(
                requirements='crcmod==1.8 --hash=%s\n' % H1, manifest=bumped))
        self.assertEqual(cm.exception.status, 400)
        self.assertIn('could not reach the package index', cm.exception.message)
        self.assertIn('crcmod==1.8', cm.exception.message)
        self.assertEqual(registry.get_driver('probe')['version'], '1.0.0')
        self.assertEqual(os.listdir(os.path.join(registry.DRIVERS_DIR, '.staging')), [])

    def test_pip_timeout_is_504(self):
        with mock.patch.object(deps.subprocess, 'run',
                               side_effect=subprocess.TimeoutExpired('pip', 1)), \
                self.assertRaises(registry.DriverStoreError) as cm:
            registry.install('probe', make_bundle())
        self.assertEqual(cm.exception.status, 504)
        self.assertFalse(registry.has('probe'))

    def test_size_cap(self):
        with mock.patch.object(deps, 'MAX_DEPS_BYTES', 10), \
                mock.patch.object(deps.subprocess, 'run', side_effect=pip_ok), \
                self.assertRaises(registry.DriverStoreError) as cm:
            registry.install('probe', make_bundle())
        self.assertEqual(cm.exception.status, 413)

    def test_bad_requirements_are_400_before_pip(self):
        for text, why in (('crcmod==1.7\n', '--hash'), (None, 'has no requirements.txt')):
            with self.subTest(why=why), \
                    mock.patch.object(deps.subprocess, 'run') as run, \
                    self.assertRaisesRegex(registry.DriverStoreError, why):
                registry.install('probe', make_bundle(requirements=text))
            run.assert_not_called()

    def test_bundle_may_not_ship_deps(self):
        with self.assertRaisesRegex(registry.DriverStoreError, r'\.deps/'):
            registry.install('probe', make_bundle(extra={'.deps/evil.py': ''}))

    def test_stale_or_missing_deps_list_as_error(self):
        with mock.patch.object(deps.subprocess, 'run', side_effect=pip_ok):
            registry.install('probe', make_bundle())
        stamp_path = os.path.join(registry.driver_dir('probe'), deps.DEPS_DIR, deps.STAMP_FILE)
        with open(stamp_path) as f:
            stamp = json.load(f)
        stamp['python'] = 'cp20'
        with open(stamp_path, 'w') as f:
            json.dump(stamp, f)
        entry = registry.list_drivers()[0]
        self.assertEqual(entry['status'], 'error')
        self.assertEqual(entry['deps']['status'], 'stale')
        self.assertIn('installed for cp20', entry['error'])
        self.assertIn('reinstall-deps', entry['error'])
        with self.assertRaises(DriverUnavailable):
            registry.get_driver('probe')

        shutil.rmtree(os.path.dirname(stamp_path))
        entry = registry.list_drivers()[0]
        self.assertEqual(entry['deps']['status'], 'missing')

        # reinstall_deps rebuilds them in place.
        with mock.patch.object(deps.subprocess, 'run', side_effect=pip_ok):
            result = registry.reinstall_deps('probe')
        self.assertEqual(result['packages'], ['crcmod==1.7'])
        self.assertEqual(registry.get_driver('probe')['deps']['status'], 'ok')
        self.assertEqual(os.listdir(os.path.join(registry.DRIVERS_DIR, '.staging')), [])

    def test_reinstall_failure_keeps_old_packages(self):
        with mock.patch.object(deps.subprocess, 'run', side_effect=pip_ok):
            registry.install('probe', make_bundle())
        failed = subprocess.CompletedProcess([], 1, stdout='ERROR: boom\n')
        with mock.patch.object(deps.subprocess, 'run', return_value=failed), \
                self.assertRaises(registry.DriverStoreError):
            registry.reinstall_deps('probe')
        self.assertEqual(registry.get_driver('probe')['deps']['status'], 'ok')

    def test_reinstall_refusals(self):
        with self.assertRaises(registry.DriverStoreError) as cm:
            registry.reinstall_deps('probe')
        self.assertEqual(cm.exception.status, 404)
        registry.install('plain', make_bundle(requirements=None,
                                              manifest=dict(MANIFEST, type='plain',
                                                            requirements=None)))
        with self.assertRaisesRegex(registry.DriverStoreError, 'declares no requirements'):
            registry.reinstall_deps('plain')
        with self.assertRaises(registry.DriverStoreError):
            registry.reinstall_deps('../etc')

    def test_loader_appends_deps_after_the_box_packages(self):
        with mock.patch.object(deps.subprocess, 'run', side_effect=pip_ok):
            registry.install('probe', make_bundle())
        bundle = registry.driver_dir('probe')
        saved = list(sys.path)
        try:
            loader.load_driver_class('probe')
            self.assertEqual(sys.path[0], bundle)
            self.assertEqual(sys.path[-1], os.path.join(bundle, deps.DEPS_DIR))
        finally:
            sys.path[:] = saved
            sys.modules.pop('lager_custom_driver_probe', None)


class TestRoutes(RegistryCase):
    def setUp(self):
        super().setUp()
        from flask import Flask
        from lager.http_handlers import drivers_handler
        app = Flask(__name__)
        drivers_handler.register_drivers_routes(app)
        self.client = app.test_client()
        p = mock.patch.object(drivers_handler, '_saved_nets', return_value=[])
        p.start()
        self.addCleanup(p.stop)

    def put(self, data):
        return self.client.put('/drivers/probe', data={
            'bundle': (io.BytesIO(data), 'bundle.zip')}, content_type='multipart/form-data')

    def test_install_reports_packages_and_listing_shows_deps(self):
        with mock.patch.object(deps.subprocess, 'run', side_effect=pip_ok):
            resp = self.put(make_bundle())
        self.assertEqual(resp.status_code, 200, resp.get_json())
        self.assertEqual(resp.get_json()['packages'], ['crcmod==1.7'])
        entry = self.client.get('/drivers').get_json()['drivers'][0]
        self.assertEqual(entry['deps']['status'], 'ok')

    def test_pip_failure_is_the_chosen_message(self):
        failed = subprocess.CompletedProcess([], 1, stdout='ERROR: No matching distribution\n')
        with mock.patch.object(deps.subprocess, 'run', return_value=failed):
            resp = self.put(make_bundle())
        self.assertEqual(resp.status_code, 400)
        self.assertIn('has no wheel for this box', resp.get_json()['error'])

    def test_reinstall_route(self):
        resp = self.client.post('/drivers/probe/deps')
        self.assertEqual(resp.status_code, 404)
        with mock.patch.object(deps.subprocess, 'run', side_effect=pip_ok):
            self.put(make_bundle())
            resp = self.client.post('/drivers/probe/deps')
        self.assertEqual(resp.status_code, 200, resp.get_json())
        self.assertEqual(resp.get_json(), {'type': 'probe', 'packages': ['crcmod==1.7']})


class TestRealPip(RegistryCase):
    """Real pip, no network: the wheel comes from the bundle's wheels/ folder."""

    def test_vendored_wheel_installs_and_imports_in_the_runner(self):
        from lager.http_handlers import drivers_handler

        wheel_name, wheel = make_wheel()
        digest = hashlib.sha256(wheel).hexdigest()
        bundle = make_bundle(
            requirements='lagertestpkg==0.1.0 --hash=sha256:%s\n' % digest,
            extra={'wheels/' + wheel_name: wheel})
        with mock.patch.dict(os.environ, {'LAGER_DRIVERS_OFFLINE': '1'}):
            result = registry.install('probe', bundle)
        self.assertEqual(result['packages'], ['lagertestpkg==0.1.0'])
        self.assertTrue(os.path.isfile(os.path.join(
            registry.driver_dir('probe'), deps.DEPS_DIR, 'lagertestpkg', '__init__.py')))

        rec = {'name': 'P1', 'role': 'probe', 'params': {}}
        value = drivers_handler.run_action('probe', rec, {}, {}, 'ping', {}, 30)
        self.assertEqual(value, {'message': 'hello from lagertestpkg'})

    def test_hash_mismatch_is_refused(self):
        wheel_name, wheel = make_wheel()
        bundle = make_bundle(
            requirements='lagertestpkg==0.1.0 --hash=%s\n' % H1,
            extra={'wheels/' + wheel_name: wheel})
        with mock.patch.dict(os.environ, {'LAGER_DRIVERS_OFFLINE': '1'}), \
                self.assertRaisesRegex(registry.DriverStoreError, 'does not match its --hash'):
            registry.install('probe', bundle)
        self.assertFalse(registry.has('probe'))

    def test_incomplete_lock_is_refused(self):
        wheel_name, wheel = make_wheel(requires=['lagernotlisted>=1'])
        digest = hashlib.sha256(wheel).hexdigest()
        bundle = make_bundle(
            requirements='lagertestpkg==0.1.0 --hash=sha256:%s\n' % digest,
            extra={'wheels/' + wheel_name: wheel})
        with mock.patch.dict(os.environ, {'LAGER_DRIVERS_OFFLINE': '1'}), \
                self.assertRaisesRegex(registry.DriverStoreError,
                                       'lagertestpkg needs lagernotlisted'):
            registry.install('probe', bundle)


